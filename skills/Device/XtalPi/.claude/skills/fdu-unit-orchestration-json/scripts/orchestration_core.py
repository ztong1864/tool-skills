def process_step(step: Dict[str, Any]) -> Dict[str, Any]:
    """Process a single step and return its execution protocol."""
    unit_type = step.get("unit_type")
    skill_input = step.get("skill_input", {})

    if not unit_type:
        raise OrchestrationError(f"Step missing unit_type")
    if not skill_input:
        raise OrchestrationError(f"Step missing skill_input")

    # Create a step object with resource_info if available
    step_data = {"skill_input": skill_input}
    if "resource_info" in step:
        step_data["resource_info"] = step["resource_info"]

    if unit_type == "exp_add_solid":
        action = call_add_solid(step_data)
    elif unit_type == "exp_pipetting":
        action = call_add_liquid(step_data)
    elif unit_type == "exp_magnetic_stirrer":
        action = call_reaction_control(step_data)
    elif unit_type == "exp_filtering_samples":
        action = call_filter(step_data)
    elif unit_type == "exp_high_filtering_samples":
        action = call_high_filter(step_data)
    else:
        raise OrchestrationError(f"Unknown unit_type: {unit_type}")

    return action



def orchestrate_steps(steps: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Orchestrate multiple steps and return the execution protocol."""
    protocol = []

    for step in steps:
        action = process_step(step)
        skill_input = step.get("skill_input", {})
        layout_code = str(action.get("layout_code", "")).strip()
        action["unit_column"] = parse_unit_column(layout_code)
        if isinstance(skill_input, dict) and "unit_row" in skill_input:
            action["unit_row"] = skill_input["unit_row"]
        protocol.append(action)
    return protocol



def generate_orchestration_json(
    step_json_path: Path,
    output_path: Path | None = None,
) -> tuple[List[Dict[str, Any]], Path]:
    """Generate orchestration JSON from step JSON."""
    step_json = read_json(step_json_path)
    steps = step_json.get("steps", [])

    if not steps:
        raise OrchestrationError("No steps found in step JSON")

    protocol = orchestrate_steps(steps)

    if output_path is None:
        timestamp = datetime.now().strftime("%Y-%m-%d-%H-%M-%S")
        output_path = OUTPUT_DIR / f"generated_protocol_{timestamp}.json"

    write_json(protocol, output_path)
    return protocol, output_path
