#!/usr/bin/env python3
# -*- coding: utf-8 -*-

from __future__ import annotations

import json
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List

# Load environment variables from .env file
env_path = Path(__file__).resolve().parents[3] / ".env"
if env_path.exists():
    from dotenv import load_dotenv

    load_dotenv(env_path)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = ROOT / "output"
SKILLS_ROOT = ROOT.parent


class OrchestrationError(Exception):
    """Exception raised for errors in orchestration."""


def parse_unit_column(layout_code: str) -> int:
    """Extract unit_column from layout_code like T-3:9."""
    match = re.search(r":(\d+)$", str(layout_code).strip())
    return int(match.group(1)) if match else 0



def read_json(path: Path) -> Any:
    """Read JSON from file."""
    return json.loads(path.read_text(encoding="utf-8-sig"))



def write_json(data: Any, path: Path) -> None:
    """Write JSON to file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")



def get_skill_path(skill_name: str) -> Path:
    """Get the path to a skill directory."""
    skill_path = SKILLS_ROOT / skill_name
    if not skill_path.exists():
        raise OrchestrationError(f"Skill not found: {skill_name}")
    return skill_path



def call_add_solid(step: Dict[str, Any]) -> Dict[str, Any]:
    """Call fdu-add-solid-json skill."""
    skill_path = get_skill_path("fdu-add-solid-json")
    script_path = skill_path / "scripts" / "generate_add_solid_json.py"

    if not script_path.exists():
        raise OrchestrationError(f"Script not found: {script_path}")

    # Create a temporary JSON file with the step data
    temp_file = skill_path / "KB" / "temp_step.json"
    write_json(step, temp_file)

    try:
        subprocess.run(
            [sys.executable, str(script_path), str(temp_file)],
            capture_output=True,
            text=True,
            check=True,
            cwd=str(skill_path),
        )

        output_files = list((skill_path / "output").glob("generated_add_solid_*.json"))
        if not output_files:
            raise OrchestrationError("No output file generated by fdu-add-solid-json")

        output_file = max(output_files, key=lambda p: p.stat().st_mtime)
        return read_json(output_file)
    except subprocess.CalledProcessError as e:
        raise OrchestrationError(f"Failed to call fdu-add-solid-json: {e.stderr}") from e



